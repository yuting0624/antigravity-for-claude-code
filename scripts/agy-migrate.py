#!/usr/bin/env python3
"""agy-migrate.py — migrate a Claude Code setup to Antigravity CLI (agy).

Read-only by default: prints a per-unit plan and exits. `--apply` performs it.

Design constraints, all of them learned the hard way from probing agy 1.1.12
(see docs/MIGRATION.md for the full findings):

  * The Claude Code config dir is treated as READ-ONLY. The only file this tool
    can ever create on the Claude side is an `AGENTS.md` symlink beside an
    existing `CLAUDE.md`, and only under --include-repos.
  * Antigravity rules are silently ignored unless their frontmatter carries
    `trigger: always_on`. No error, no warning — they just never load. So
    migrated memory is REWRITTEN with that frontmatter, never stripped.
  * Workspace customizations (`.agents/`) only load when the session is bound
    to an agy project. Writing `.agents/rules/` without registering the repo in
    ~/.gemini/config/projects/ produces rules that never fire.
  * `~/` is NOT expanded in the global skills.json, so entry paths are absolute.
  * `agy plugin import claude` only scans ~/.claude/plugins/<name>/ one level
    deep, which no modern Claude Code install matches — and it does not follow
    symlinks. It needs no auth, though, so we COPY the real plugins flat into a
    staging HOME, run the native importer there, and repair its output.
"""

