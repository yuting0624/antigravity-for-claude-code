def do_uninstall(apply_):
    mf = Manifest()
    n = 0
    for p in mf.symlinks:
        if os.path.islink(p):
            print(f"  remove symlink {p}")
            n += 1
            if apply_:
                os.unlink(p)
    for p in mf.files:
        if os.path.isfile(p) and (MARKER in read_text(p) or p.endswith(".json")):
            print(f"  remove file    {p}")
            n += 1
            if apply_:
                os.remove(p)
    for p in mf.trees:
        # Only ours: recorded because we created the whole tree in one copytree.
        if os.path.isdir(p):
            print(f"  remove tree    {p}")
            n += 1
            if apply_:
                shutil.rmtree(p)
    for path, pointers in mf.json_keys.items():
        d = read_json(path, None)
        if not d:
            continue
        for pointer, keys in pointers.items():
            node, parent, last = d, None, None
            for part in ([] if pointer == "" else pointer.split(".")):
                parent, last = node, part
                node = node.get(part) if isinstance(node, dict) else None
                if node is None:
                    break
            if node is None:
                continue
            for k in keys:
                if isinstance(node, dict) and k in node:
                    print(f"  unset {path} :: {pointer}.{k}")
                    n += 1
                    if apply_:
                        del node[k]
                elif isinstance(node, list):
                    before = len(node)
                    # Entries are plain strings (trustedWorkspaces), {"path": …}
                    # (skills.json) or {"name": …} (import_manifest).
                    node[:] = [x for x in node
                               if x != k and not (isinstance(x, dict)
                                                  and k in (x.get("path"), x.get("name")))]
                    if len(node) != before:
                        print(f"  unset {path} :: {pointer}[{k}]")
                        n += 1
        if apply_:
            write_json(path, d)
    for p in mf.created_json:
        d = read_json(p, None)
        if d is None:
            continue
        if isinstance(d, dict) and any(v for v in d.values()):
            print(f"  keep file      {p} (still holds entries we did not add)")
            continue
        print(f"  remove file    {p}")
        n += 1
        if apply_:
            os.remove(p)
    for p in sorted(mf.dirs, key=len, reverse=True):
        if os.path.isdir(p) and not os.listdir(p):
            print(f"  rmdir          {p}")
            n += 1
            if apply_:
                os.rmdir(p)
    print(f"\n{n} item(s) " + ("removed" if apply_ else "would be removed (--apply to do it)"))
    if apply_:
        for f in (manifest_path(),):
            if os.path.exists(f):
                os.remove(f)
    return 0


# --- report ------------------------------------------------------------------

SYM = {"ok": "✓", "warn": "⚠", "skip": "·", "err": "✗"}


def print_report(plan, apply_):
    for unit in UNITS:
        items = plan.by_unit(unit)
        if not items:
            continue
        print(f"\n{C['hdr']}[{unit}]{C['off']}")
        for i in items:
            col = C.get(i["level"], "")
            print(f"  {col}{SYM.get(i['level'],'·')}{C['off']} "
                  f"{i['action']:<20} {i['target']}")
            if i["detail"]:
                print(f"      {i['detail']}")
    c = plan.counts()
    print(f"\n{C['hdr']}Total{C['off']}: {c.get('ok',0)} to apply / {c.get('warn',0)} warning(s) / "
          f"{c.get('skip',0)} skipped")
    if not apply_:
        print(f"\n{C['warn']}This was a dry run. Pass --apply to perform it.{C['off']}")


# --- main --------------------------------------------------------------------

class _Parser(argparse.ArgumentParser):
    """argparse exits 2 on a bad flag; the plugin's shared table calls 2 "agy
    failed" and 1 "usage error". Conform to the table rather than add an exception."""

    def error(self, message):
        self.print_usage(sys.stderr)
        sys.stderr.write(f"{self.prog}: error: {message}\n")
        sys.exit(1)


def main(argv=None):
    ap = _Parser(
        prog="agy-migrate",
        description="Migrate a Claude Code setup (skills, memory, CLAUDE.md, MCP, "
                    "plugins, permissions) to the Antigravity CLI.")
    ap.add_argument("--apply", action="store_true", help="actually write (default is a dry run)")
    ap.add_argument("--only", default="", help=f"limit to these units: {','.join(UNITS)}")
    ap.add_argument("--skip", default="", help="exclude these units")
    ap.add_argument("--include-repos", action="store_true",
                    help="also write inside git repos (AGENTS.md symlink, .agents/rules)")
    ap.add_argument("--include-orphan-memory", action="store_true",
                    help="fold memory whose source directory no longer exists into global rules")
    ap.add_argument("--no-register-projects", action="store_true",
                    help="skip agy project registration (workspace .agents/ then stays inert)")
    ap.add_argument("--roots", default="",
                    help="comma-separated roots to scan for CLAUDE.md / .mcp.json "
                         "(default: the real project paths recorded in ~/.claude.json)")
    ap.add_argument("--apply-permissions", action="store_true",
                    help="actually write the translated allow-list to settings.json. Off by "
                         "default: Claude's allow-list holds whole command lines, so any "
                         "translation widens the grant")
    ap.add_argument("--uninstall", action="store_true", help="remove what a previous run generated")
    ap.add_argument("--json", action="store_true", help="emit a machine-readable plan")
    args = ap.parse_args(argv)

    if args.uninstall:
        return do_uninstall(args.apply)

    # 18: a missing prerequisite, not a usage error and not an agy failure.
    if not os.path.isdir(claude_dir()):
        print(f"{C['err']}No Claude Code config directory at {claude_dir()}{C['off']}")
        return 18
    if not os.path.isdir(gemini_root()):
        print(f"{C['err']}No Antigravity install at {gemini_root()} "
              f"— run agy once first{C['off']}")
        return 18

    only = {u for u in args.only.split(",") if u} or set(UNITS)
    skip = {u for u in args.skip.split(",") if u}
    unknown = sorted((only | skip) - set(UNITS))
    if unknown:
        # Exit 1 = usage error, per the shared table. Silently planning nothing would
        # be indistinguishable from "you have nothing to migrate".
        print(f"{C['err']}unknown unit(s): {', '.join(unknown)}{C['off']}\n"
              f"known units: {', '.join(UNITS)}")
        return 1
    active = [u for u in UNITS if u in only and u not in skip]

    roots = [os.path.abspath(os.path.expanduser(r))
             for r in args.roots.split(",") if r] or default_roots()

    print(f"{C['hdr']}Claude Code{C['off']}  {claude_dir()}")
    print(f"{C['hdr']}Antigravity{C['off']}  {gemini_config()}")
    print(f"{C['hdr']}Scanning{C['off']}     {len(roots)} root(s)"
          f"{'' if args.roots else ' (override with --roots)'}")

    mf = Manifest()
    plan = Plan()
    if "plugins" in active:
        unit_plugins(plan, mf)
    if "skills" in active:
        unit_skills(plan, mf)
    if "claudemd" in active:
        unit_claudemd(plan, mf, roots, args.include_repos)
    if "memory" in active:
        unit_memory(plan, mf, args.include_orphan_memory, args.include_repos,
                    not args.no_register_projects)
    if "mcp" in active:
        unit_mcp(plan, mf, roots)
    if "settings" in active:
        unit_settings(plan, mf, args.apply_permissions)

    if args.json:
        print(json.dumps([{k: v for k, v in i.items() if k != "fn"}
                          for i in plan.items], indent=2, ensure_ascii=False))
        return 0

    print_report(plan, args.apply)
    if not args.apply:
        return 0

    dest = backup([gemini_config(), agy_settings_path()])
    print(f"\nBackup: {dest}")
    failed = []
    try:
        for i in plan.items:
            if i["level"] != "ok" or not i["fn"]:
                continue
            try:
                res = i["fn"]()
            except Exception as e:                       # keep going; report at the end
                res, e_txt = False, f"{type(e).__name__}: {e}"
                print(f"  {C['err']}✗{C['off']} {i['action']} {i['target']} — {e_txt}")
            else:
                mark = C["err"] + "✗" if res is False else C["ok"] + "✓"
                print(f"  {mark}{C['off']} {i['action']} {i['target']}")
            if res is False:
                failed.append(f"{i['unit']}/{i['action']}")
            # Saved per step, not once at the end: a crash halfway through must still
            # leave --uninstall able to find everything written so far.
            mf.save()
    finally:
        mf.runs.append({"at": now_iso(), "units": active, "backup": dest,
                        "failed": failed})
        mf.save()

    if failed:
        print(f"\n{C['err']}{len(failed)} step(s) failed:{C['off']} {', '.join(failed)}")
        print(f"Everything that did succeed is tracked; "
              f"revert with: agy-migrate --uninstall --apply")
        print(f"Backup of the previous state: {dest}")
        # 17, not 2: argparse already exits 2 for a bad flag, and the plugin's shared
        # table calls 2 "agy failed". Neither is what happened here.
        return 17
    print("\nDone. To revert: agy-migrate --uninstall --apply")
    return 0


if __name__ == "__main__":
    sys.exit(main())
