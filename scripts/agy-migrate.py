def home():
    return os.path.expanduser("~")


def claude_dir():
    """Honour CLAUDE_CONFIG_DIR — this user runs a second profile at ~/.claude-pro."""
    return os.path.abspath(os.path.expanduser(
        os.environ.get("CLAUDE_CONFIG_DIR") or os.path.join(home(), ".claude")))


def claude_json_path():
    """.claude.json sits INSIDE a relocated config dir, but beside the default one."""
    inside = os.path.join(claude_dir(), ".claude.json")
    if os.path.isfile(inside):
        return inside
    return os.path.join(os.path.dirname(claude_dir()), ".claude.json")


