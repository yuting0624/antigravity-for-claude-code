# --- unit: MCP ---------------------------------------------------------------

UNEXPANDED = re.compile(r"\$\{?CLAUDE_[A-Z_]+\}?")


def translate_mcp(spec):
    """Claude mcpServers entry -> Antigravity. Returns (entry, warnings)."""
    warns = []
    blob = json.dumps(spec)
    if UNEXPANDED.search(blob):
        return None, ["references a Claude Code variable Antigravity never sets "
                      f"({UNEXPANDED.search(blob).group(0)})"]
    url = spec.get("serverUrl") or spec.get("url") or spec.get("httpUrl")
    if url:
        if spec.get("headers"):
            warns.append("headers dropped: unsupported")
        return {"serverUrl": url}, warns
    cmd = spec.get("command")
    if not cmd:
        return None, ["neither command nor url"]
    out = {"command": cmd}
    if spec.get("args"):
        out["args"] = spec["args"]
    if spec.get("env"):
        out["env"] = spec["env"]
    if not shutil.which(cmd) and not os.path.isabs(cmd):
        warns.append(f"`{cmd}` is not on PATH (agy will fail to start it)")
    return out, warns


def collect_mcp(roots):
    """Every place Claude Code keeps the USER's MCP servers, plus the desktop config.

    Vendored plugin catalogues are excluded by construction — see below.
    """
    found = {}   # name -> (spec, source)

    def take(name, spec, source):
        if name not in found:
            found[name] = (spec, source)

    roots_abs = [os.path.abspath(r) for r in roots]

    def in_roots(path):
        p = os.path.abspath(path)
        return any(p == r or p.startswith(r.rstrip(os.sep) + os.sep) for r in roots_abs)

    cj = read_json(claude_json_path(), None) or {}
    for proj, cfg in (cj.get("projects") or {}).items():
        if not in_roots(proj):
            continue
        for name, spec in (cfg.get("mcpServers") or {}).items():
            take(name, spec, f".claude.json:{proj}")
    for name, spec in (cj.get("mcpServers") or {}).items():
        take(name, spec, ".claude.json")

    # Deliberately NOT a filesystem walk. `.mcp.json` sits at a project root by
    # convention, and walking $HOME found vendored catalogues in two separate caches
    # (~/.claude/plugins/marketplaces/ and Claude Desktop's rpm/plugin_*/) — 40 servers
    # the user had never configured. The real project roots are already recorded, so
    # consult exactly those and nothing can smuggle entries in.
    candidates = list(roots) + [d for d in (cj.get("projects") or {})
                                if os.path.isdir(d) and in_roots(d)]
    for d in dict.fromkeys(os.path.abspath(c) for c in candidates):
        if under_excluded(d):
            continue
        p = os.path.join(d, ".mcp.json")
        for name, spec in ((read_json(p, None) or {}).get("mcpServers") or {}).items():
            take(name, spec, p)

    # The desktop app's config is a single global file with no project scope, so
    # --roots cannot meaningfully narrow it.
    desktop = os.path.join(home(), "Library", "Application Support", "Claude",
                           "claude_desktop_config.json")
    for name, spec in ((read_json(desktop, None) or {}).get("mcpServers") or {}).items():
        take(name, spec, "claude_desktop_config.json")

    return found


def unit_mcp(plan, mf, roots):
    found = collect_mcp(roots)
    if not found:
        plan.add("mcp", "skip", "no-op", "-", "no MCP servers defined on the Claude side")
        return
    dest = os.path.join(gemini_config(), "mcp_config.json")
    current = (read_json(dest, None) or {}).get("mcpServers") or {}
    to_add = {}
    for name, (spec, source) in sorted(found.items()):
        if name in current:
            plan.add("mcp", "skip", "name-taken", name,
                     f"name already taken in Antigravity; not overwriting ({source})")
            continue
        entry, warns = translate_mcp(spec)
        if entry is None:
            plan.add("mcp", "warn", "unmigratable", name, "; ".join(warns))
            continue
        for w in warns:
            plan.add("mcp", "warn", "check", name, w)
        to_add[name] = entry
        kind = "remote" if "serverUrl" in entry else "stdio"
        plan.add("mcp", "ok", "add", name, f"{kind} <- {source}")

    if not to_add:
        return

    def fn():
        cur = read_json(dest, None) or {}
        servers = cur.get("mcpServers") or {}
        for name, entry in to_add.items():
            if name in servers:
                continue
            servers[name] = entry
            mf.note_key(dest, "mcpServers", name)
        cur["mcpServers"] = servers
        write_json(dest, cur)

    plan.add("mcp", "ok", "write", dest, f"append {len(to_add)} server(s)", fn)


# --- unit: settings / permissions -------------------------------------------

BASH_RULE = re.compile(r"^Bash\((.+)\)$")
PLAIN_WORD = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")


def translate_permission(rule):
    """Claude `Bash(...)` -> agy `command(<prefix>)`, or None when unmappable.

    Claude's allow-list stores whole command LINES — including quoted prompts and
    escaped parens — not command prefixes. Copying them across verbatim yields
    entries that can never match. So we keep only the leading executable plus one
    plain sub-command word, which is the granularity agy's `command()` matches at.

    This WIDENS the grant (`Bash(git diff:*)` becomes `command(git diff)`), which
    is why the caller never writes these to settings.json without an explicit flag.
    """
    m = BASH_RULE.match(rule.strip())
    if not m:
        return None
    inner = re.sub(r":\*$", "", m.group(1).strip()).strip()
    if not inner or inner.startswith("$"):
        return None
    toks = inner.split()
    if not toks:
        return None
    head = toks[0].rstrip("*")
    # A quote or shell metacharacter in the executable position is not a command.
    if not head or any(ch in head for ch in "|&;<>$`\"'()"):
        return None
    out = head
    if len(toks) > 1 and PLAIN_WORD.match(toks[1]):
        out = f"{head} {toks[1]}"
    return f"command({out})"


def absorb_prefixes(cmds):
    """Drop `command(git diff)` when `command(git)` is already granted."""
    inner = sorted({c[len("command("):-1] for c in cmds})
    keep = [c for c in inner
            if not any(c != k and c.startswith(k + " ") for k in inner)]
    return [f"command({c})" for c in keep]


